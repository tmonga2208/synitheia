const fs = require('node:fs');
const path = require('node:path');
const {
  AndroidConfig,
  createRunOncePlugin,
  withAndroidManifest,
  withDangerousMod,
} = require('expo/config-plugins');

/**
 * Sharing an image or a message into the app, on Android.
 *
 * app.json used to put a share filter on MainActivity, so the app appeared in Android's share
 * sheet. But a share arrives as an intent with extras and no url, React Native only ever
 * hears about urls, and so whatever was shared was dropped: the app opened wherever it last
 * was. It advertised something it did not do.
 *
 * This is the same answer the Health Connect policy link got (withHealthConnectRationale.js):
 * a tiny native activity receives the intent and re-launches the app at a link the router
 * understands. Doing it in an activity of its own, rather than teaching MainActivity to read
 * the extras, keeps MainActivity untouched and reuses a path that has been seen to work with
 * the app running, stopped, and reclaimed in the background.
 *
 * iOS is not covered. Sharing into an iOS app needs a share extension, which is a separate
 * target with its own signing, and is out of reach for an unsigned sideloaded build.
 */

const ACTIVITY = 'ShareTargetActivity';
const SEND = 'android.intent.action.SEND';

function shareTargetSource(packageName, scheme) {
  return `package ${packageName}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle
import androidx.core.content.IntentCompat
import java.io.File
import java.util.UUID

/**
 * GENERATED by plugins/withShareTarget.js. Edit the plugin, not this file.
 *
 * Receives what another app shares to this one: an image, or some text. The intent carries
 * no url, so React Native cannot route it; this turns it into a link to the import screen
 * and gets out of the way.
 *
 * Nothing here uploads anything. A shared image is copied into the app's own cache, because
 * permission to read the original lasts only as long as this activity does, and the import
 * screen shows what arrived and waits for the user to tap.
 */
class ${ACTIVITY} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)

    val link = linkFor(intent)
    if (link != null) {
      startActivity(
        Intent(Intent.ACTION_VIEW, link)
          // This app only: the link must never be answered by another app that happens to
          // claim the same scheme.
          .setPackage(packageName)
          .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
      )
    }
    finish()
  }

  /** The import screen's link for this share, or null if this was not a share at all. */
  private fun linkFor(shared: Intent?): Uri? {
    if (shared == null || shared.action != Intent.ACTION_SEND) return null

    val screen = Uri.parse("${scheme}://expenses/new").buildUpon()

    // IntentCompat, not Intent.getParcelableExtra: the typed platform call throws on some
    // Android 13 builds, and the untyped one is deprecated.
    val stream = IntentCompat.getParcelableExtra(shared, Intent.EXTRA_STREAM, Uri::class.java)
    if (stream != null) {
      val copy = copyToCache(stream, contentResolver.getType(stream) ?: shared.type)
        ?: return screen.appendQueryParameter("sharedError", "unreadable").build()
      return screen.appendQueryParameter("sharedImage", Uri.fromFile(copy).toString()).build()
    }

    val text = shared.getStringExtra(Intent.EXTRA_TEXT)?.trim().orEmpty()
    if (text.isEmpty()) {
      return screen.appendQueryParameter("sharedError", "unreadable").build()
    }
    return screen.appendQueryParameter("sharedText", text.take(MAX_TEXT)).build()
  }

  private fun copyToCache(source: Uri, type: String?): File? {
    // Only what the importer takes. Anything else would be refused by the server later,
    // after an upload, with a worse message.
    val extension = EXTENSIONS[type] ?: return null

    val folder = File(cacheDir, FOLDER)
    // One share at a time: whatever an earlier one left here is no longer wanted.
    folder.deleteRecursively()
    if (!folder.mkdirs()) return null

    // A name nobody chose. The import screen accepts a file only if it looks like this, so
    // a forged link cannot point it at anything else on the device.
    val copy = File(folder, UUID.randomUUID().toString() + "." + extension)

    return try {
      val input = contentResolver.openInputStream(source) ?: return null
      var total = 0L
      input.use { from ->
        copy.outputStream().use { to ->
          val buffer = ByteArray(64 * 1024)
          while (total <= MAX_BYTES) {
            val read = from.read(buffer)
            if (read < 0) break
            total += read
            to.write(buffer, 0, read)
          }
        }
      }

      if (total == 0L || total > MAX_BYTES) {
        copy.delete()
        null
      } else {
        copy
      }
    } catch (error: Exception) {
      // The other app withdrew the image, or it was never readable. Nothing to import.
      copy.delete()
      null
    }
  }

  private companion object {
    private const val FOLDER = "shared"
    private const val MAX_BYTES = 15L * 1024 * 1024
    private const val MAX_TEXT = 4000

    private val EXTENSIONS = mapOf(
      "image/jpeg" to "jpg",
      "image/png" to "png",
      "image/webp" to "webp",
      "image/gif" to "gif",
    )
  }
}
`;
}

/**
 * Adds the share activity to a parsed AndroidManifest, and takes any share filter off
 * MainActivity. Safe to apply twice.
 *
 * The second half matters: with the filter in both places Android would list the app twice
 * in the share sheet, and one of the two would still drop what it was given.
 */
function applyShareTarget(androidManifest) {
  const application = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);

  for (const activity of application.activity ?? []) {
    if (activity.$['android:name'] !== '.MainActivity') continue;
    activity['intent-filter'] = (activity['intent-filter'] ?? []).filter(
      (filter) => !(filter.action ?? []).some((action) => action.$['android:name'] === SEND),
    );
  }

  application.activity = (application.activity ?? []).filter(
    (activity) => activity.$['android:name'] !== `.${ACTIVITY}`,
  );
  application.activity.push({
    $: {
      'android:name': `.${ACTIVITY}`,
      // Another app starts it; it can only start an exported activity.
      'android:exported': 'true',
      'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
      'android:excludeFromRecents': 'true',
      'android:noHistory': 'true',
    },
    'intent-filter': [
      {
        action: [{ $: { 'android:name': SEND } }],
        category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
        data: [{ $: { 'android:mimeType': 'image/*' } }, { $: { 'android:mimeType': 'text/plain' } }],
      },
    ],
  });

  return androidManifest;
}

const withShareTarget = (config, props = {}) => {
  const scheme = props.scheme ?? (Array.isArray(config.scheme) ? config.scheme[0] : config.scheme);
  if (!scheme) {
    throw new Error('withShareTarget: expo.scheme must be set, or pass { scheme }');
  }

  config = withAndroidManifest(config, (manifestConfig) => {
    manifestConfig.modResults = applyShareTarget(manifestConfig.modResults);
    return manifestConfig;
  });

  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const packageName = modConfig.android?.package;
      if (!packageName) {
        throw new Error('withShareTarget: expo.android.package must be set');
      }

      const directory = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...packageName.split('.'),
      );
      await fs.promises.mkdir(directory, { recursive: true });
      await fs.promises.writeFile(
        path.join(directory, `${ACTIVITY}.kt`),
        shareTargetSource(packageName, scheme),
      );

      return modConfig;
    },
  ]);
};

module.exports = createRunOncePlugin(withShareTarget, 'with-share-target', '1.0.0');
module.exports.applyShareTarget = applyShareTarget;
module.exports.shareTargetSource = shareTargetSource;
