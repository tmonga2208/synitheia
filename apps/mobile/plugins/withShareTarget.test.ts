import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { URL, fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

interface Named {
  $: Record<string, string>;
}

interface Filter {
  action?: Named[];
  category?: Named[];
  data?: Named[];
}

interface ActivityNode extends Named {
  'intent-filter'?: Filter[];
}

interface Manifest {
  manifest: {
    $: Record<string, string>;
    application: (Named & { activity?: ActivityNode[] })[];
  };
}

// CommonJS, loaded with `require`, exactly as prebuild loads it.
const plugin = createRequire(import.meta.url)('./withShareTarget.js') as {
  applyShareTarget: (manifest: Manifest) => Manifest;
  shareTargetSource: (packageName: string, scheme: string) => string;
};

const SEND = 'android.intent.action.SEND';

const sendFilter = (): Filter => ({
  action: [{ $: { 'android:name': SEND } }],
  category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
  data: [{ $: { 'android:mimeType': 'image/*' } }, { $: { 'android:mimeType': 'text/plain' } }],
});

/** A manifest as Expo writes it, cut down. `withSend` is what app.json used to produce. */
function manifest({ withSend = false } = {}): Manifest {
  return {
    manifest: {
      $: { 'xmlns:android': 'http://schemas.android.com/apk/res/android' },
      application: [
        {
          $: { 'android:name': '.MainApplication' },
          activity: [
            {
              $: { 'android:name': '.MainActivity', 'android:exported': 'true' },
              'intent-filter': [
                {
                  action: [{ $: { 'android:name': 'android.intent.action.MAIN' } }],
                  category: [{ $: { 'android:name': 'android.intent.category.LAUNCHER' } }],
                },
                ...(withSend ? [sendFilter()] : []),
              ],
            },
          ],
        },
      ],
    },
  };
}

const activities = (m: Manifest) => m.manifest.application[0]!.activity ?? [];
const named = (m: Manifest, name: string) => activities(m).filter((a) => a.$['android:name'] === name);
const actionsOf = (activity: ActivityNode) =>
  (activity['intent-filter'] ?? []).flatMap((f) => (f.action ?? []).map((a) => a.$['android:name']));

describe('applyShareTarget', () => {
  it('declares an activity other apps can share an image or text to', () => {
    const [target] = named(plugin.applyShareTarget(manifest()), '.ShareTargetActivity');

    expect(target).toBeDefined();
    // Another app starts it, so it has to be exported.
    expect(target!.$['android:exported']).toBe('true');
    // It shows nothing and must not linger in the task or in recents.
    expect(target!.$['android:noHistory']).toBe('true');
    expect(target!.$['android:excludeFromRecents']).toBe('true');
    expect(target!.$['android:theme']).toBe('@android:style/Theme.Translucent.NoTitleBar');

    const filters = target!['intent-filter'] ?? [];
    expect(filters).toHaveLength(1);
    expect(filters[0]!.action!.map((a) => a.$['android:name'])).toEqual([SEND]);
    expect(filters[0]!.category!.map((c) => c.$['android:name'])).toEqual([
      'android.intent.category.DEFAULT',
    ]);
    expect(filters[0]!.data!.map((d) => d.$['android:mimeType'])).toEqual(['image/*', 'text/plain']);
  });

  it('takes the share filter off MainActivity, where nothing ever handled it', () => {
    const result = plugin.applyShareTarget(manifest({ withSend: true }));
    const [main] = named(result, '.MainActivity');

    // Left there, Android would offer the app twice and one of the two would do nothing.
    expect(actionsOf(main!)).toEqual(['android.intent.action.MAIN']);
    expect(actionsOf(named(result, '.ShareTargetActivity')[0]!)).toEqual([SEND]);
  });

  it('leaves the launcher entry alone', () => {
    const [main] = named(plugin.applyShareTarget(manifest()), '.MainActivity');
    expect(main!['intent-filter']).toHaveLength(1);
    expect(main!.$['android:exported']).toBe('true');
  });

  it('is safe to apply twice', () => {
    const twice = plugin.applyShareTarget(plugin.applyShareTarget(manifest({ withSend: true })));
    expect(named(twice, '.ShareTargetActivity')).toHaveLength(1);
    expect(activities(twice)).toHaveLength(2);
  });
});

describe('shareTargetSource', () => {
  const source = plugin.shareTargetSource('com.example.app', 'example');

  it('is a Kotlin activity in the app’s own package, marked as generated', () => {
    expect(source.startsWith('package com.example.app\n')).toBe(true);
    expect(source).toContain('class ShareTargetActivity : Activity()');
    expect(source).toContain('GENERATED by plugins/withShareTarget.js');
  });

  it('hands the app a link to the import screen, and only to this app', () => {
    expect(source).toContain('Uri.parse("example://expenses/new")');
    // Never answered by another app that happens to claim the same scheme.
    expect(source).toContain('.setPackage(packageName)');
    expect(source).toContain('"sharedImage"');
    expect(source).toContain('"sharedText"');
    expect(source).toContain('"sharedError"');
  });

  it('copies a shared image into the app’s own cache under a name nobody chose', () => {
    expect(source).toContain('File(cacheDir, FOLDER)');
    expect(source).toContain('private const val FOLDER = "shared"');
    expect(source).toContain('UUID.randomUUID()');
    // The types the importer accepts, and nothing else.
    expect(source).toContain('"image/jpeg" to "jpg"');
    expect(source).toContain('"image/png" to "png"');
    expect(source).toContain('"image/webp" to "webp"');
    expect(source).toContain('"image/gif" to "gif"');
  });

  it('bounds what it will take', () => {
    expect(source).toContain('private const val MAX_BYTES = 15L * 1024 * 1024');
    expect(source).toContain('private const val MAX_TEXT = 4000');
  });
});

describe('app.json', () => {
  const config = JSON.parse(
    readFileSync(fileURLToPath(new URL('../app.json', import.meta.url)), 'utf8'),
  ) as { expo: { plugins: unknown[]; android: { intentFilters?: unknown } } };

  it('uses the plugin', () => {
    expect(config.expo.plugins).toContain('./plugins/withShareTarget');
  });

  it('no longer asks MainActivity to receive shares', () => {
    // Expo puts `android.intentFilters` on MainActivity. That is where the share used to go,
    // and be dropped.
    expect(config.expo.android.intentFilters).toBeUndefined();
  });
});
